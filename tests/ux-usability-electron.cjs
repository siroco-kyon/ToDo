    await js('window.api.teamGetDashboard=window.originalTeam;void 0')
    await click('再試行')
    await until('document.body.innerText.includes("メンバーの負荷")&&!document.body.innerText.includes("UXチーム取得失敗")','Team retry')
    await main.loadURL(fixture.origin+'/?view=progress')
