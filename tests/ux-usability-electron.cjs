    await js('window.originalTeam=window.api.teamGetDashboard;window.api.teamGetDashboard=async()=>{throw new Error("UXチーム取得失敗")};Array.from(document.querySelectorAll("[role=tab]")).find(e=>e.textContent==="チーム").click();void 0')
