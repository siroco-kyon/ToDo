    await js('document.querySelector("main details summary").click();(()=>{const s=document.querySelector("select[aria-label=進捗を書くタスク]");s.value=s.querySelectorAll("option")[1].value;s.dispatchEvent(new Event("change",{bubbles:true}));})();void 0')
